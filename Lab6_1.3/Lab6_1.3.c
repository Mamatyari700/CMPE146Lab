#include "ti_msp_dl_config.h"
#include <stdint.h>
#include <stdbool.h>

#define BAUD_RATE   9600UL       
#define UART_CYCLE_TIME  (CPUCLK_FREQ / BAUD_RATE)

void tx_high(void)
{
    DL_GPIO_setPins(GPIOA, DL_GPIO_PIN_10);
}

void tx_low(void)
{
    DL_GPIO_clearPins(GPIOA, DL_GPIO_PIN_10);
}

void tx_bit_delay(void)
{
    delay_cycles(UART_CYCLE_TIME);
}

void tx_send_byte(uint8_t byte)
{
    tx_low(); //start bit
    tx_bit_delay();

    for (int i = 0; i < 8; i++) {//1 byte data(send from LSB)
        if (byte & 0x01) {
            tx_high();
        } else {
            tx_low();
        }
        tx_bit_delay();
        byte >>= 1; //shift the data 1bit to right
    }

    tx_high(); //stop bit
    tx_bit_delay();
}

void send_message(char *msg)
{
    while (*msg != '\0') {
        tx_send_byte((uint8_t)*msg);
        msg++;
    }
}

